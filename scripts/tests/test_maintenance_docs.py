"""test_maintenance_docs.py — the maintenance docs say what the code still does.

`docs/maintenance/qoder-format.md` is *generated*: `qcut format` prints the format
surface from the registry at the top of `qcut-sync.py`, and the document carries
that output between markers. That makes it the one doc that can be trusted without
reading it — as long as it is still in step with the code. If it drifts, the
document becomes a description of a parser that no longer exists, which is worse
than no document because it is read as authoritative.

The other cases hold the surrounding promises that are equally checkable: the
assets are reachable (an orphan maintenance doc is one nobody regenerates), and
the CI matrix pins the version the project actually declares rather than a version
someone remembered.

Standard library only; nothing is written and no database is opened.
"""

import importlib.util
import re
import sys
import unittest
from pathlib import Path
import _hermetic  # noqa: E402,F401 -- tripwire: the suite must never open the real database

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "scripts"
DOCS = ROOT / "docs" / "maintenance"
sys.path.insert(0, str(SCRIPTS))

FORMAT_DOC = DOCS / "qoder-format.md"
BEGIN, END = "<!-- BEGIN GENERATED -->", "<!-- END GENERATED -->"


def load_sync():
    spec = importlib.util.spec_from_file_location(
        "qcut_sync_maintenance_test", str(SCRIPTS / "qcut-sync.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


sync = load_sync()


def generated_block(text):
    """The text between the markers, or None when the markers are not a pair."""
    m = re.search(re.escape(BEGIN) + r"\n(.*?)\n?" + re.escape(END), text, re.S)
    return m.group(1) if m else None


def python_versions_in_ci():
    ci = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    m = re.search(r"python-version:\s*\[([^\]]*)\]", ci)
    if not m:
        return []
    return [v.strip().strip("'\"") for v in m.group(1).split(",") if v.strip()]


def declared_floor():
    """`requires-python` from pyproject.toml — the version CI must pin first.

    Read with a pattern rather than `ast.parse`: pyproject is TOML, and parsing it
    as Python is how this file once produced a SyntaxError instead of a finding.
    """
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    m = re.search(r'requires-python\s*=\s*"([^"]+)"', text)
    return m.group(1).lstrip(">=~=<^ ") if m else None


def markdown_links(text):
    """The ``[label](target)`` links in a document, ignoring http(s) ones."""
    return [t for t in re.findall(r"\]\(([^)#][^)]*)\)", text)
            if not t.startswith(("http://", "https://"))]


class GeneratedFormatDocTest(unittest.TestCase):
    def test_the_generated_block_is_what_the_code_prints(self):
        text = FORMAT_DOC.read_text(encoding="utf-8")
        block = generated_block(text)
        self.assertIsNotNone(
            block, f"{FORMAT_DOC.name} lost its {BEGIN} / {END} markers — "
                   "`qcut format --write` splices between them and cannot find them")
        self.assertEqual(
            block.strip(), sync.format_doc().strip(),
            "the format document no longer matches the registry: run "
            "`qcut format --write` and commit it with the registry change")

    def test_the_router_names_the_regeneration_command(self):
        """A reader who finds a stale block has to be told the command where they
        are looking — the generated block itself carries no prose to edit."""
        maintenance = (ROOT / "MAINTENANCE.md").read_text(encoding="utf-8")
        self.assertIn("format --write", maintenance)

    def test_the_generated_doc_points_back_at_the_router(self):
        """"Generated by `qcut format`" is only useful if it says where the
        procedure lives. The doc sits in docs/maintenance/, so a link that says
        "see docs/maintenance/" points the reader at the folder it is in."""
        text = FORMAT_DOC.read_text(encoding="utf-8")
        self.assertIn("MAINTENANCE.md", text)

    def test_the_registry_block_is_not_restated_in_agents_md(self):
        """AGENTS.md points at the registry instead of copying it — a second copy
        of the field list is a second thing that goes stale.

        The markers are names only *upstream* uses (`cache_read_input_tokens`,
        `customProviderId`), never column names: `input_tokens` is a column this
        project owns and legitimately discusses in its rules, so forbidding it
        would be a rule about vocabulary rather than about coupling.
        """
        agents = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
        self.assertIn("does not list the fields", agents)
        for upstream_only in ("cache_read_input_tokens", "customProviderId",
                              "cache_creation_input_tokens"):
            self.assertNotIn(
                upstream_only, agents,
                f"AGENTS.md restates the upstream key `{upstream_only}`; the "
                "registry and docs/maintenance/qoder-format.md own that list")


class AssetsReachableTest(unittest.TestCase):
    def test_every_maintenance_asset_is_linked_from_the_router(self):
        maintenance = (ROOT / "MAINTENANCE.md").read_text(encoding="utf-8")
        orphans = sorted(p.name for p in DOCS.glob("*.md")
                         if p.name not in maintenance)
        self.assertEqual(
            orphans, [],
            f"unreferenced maintenance assets: {orphans} — an asset no router "
            "names is an asset nobody regenerates")

    def test_every_link_resolves(self):
        """A router that points at a moved file is how an orphan asset is born.

        Relative links are resolved against the *document's own directory* — a
        link inside `docs/maintenance/` reaching the repo root is two levels up,
        and a checker that assumed the root would report it broken (or, worse,
        never check it at all).
        """
        docs = [ROOT / "MAINTENANCE.md", ROOT / "MAINTENANCE.zh-CN.md"] + \
            sorted(DOCS.glob("*.md"))
        for path in docs:
            text = path.read_text(encoding="utf-8")
            for target in markdown_links(text):
                if target.startswith("<") or target.endswith((".com", "/")):
                    continue
                resolved = (path.parent / target).resolve()
                self.assertTrue(
                    resolved.exists(),
                    f"{path.name} links to {target!r}, which resolves to "
                    f"{resolved} and does not exist")

    def test_the_bilingual_router_pair_agrees(self):
        en = (ROOT / "MAINTENANCE.md").read_text(encoding="utf-8")
        zh = (ROOT / "MAINTENANCE.zh-CN.md").read_text(encoding="utf-8")
        head = lambda t: [l.strip() for l in t.splitlines() if l.startswith("## ")]
        self.assertEqual(len(head(en)), len(head(zh)),
                         "the two routers no longer have the same sections: "
                         f"{head(en)} vs {head(zh)}")
        # The asset table is the load-bearing part, so its file names must match
        # across languages rather than the prose.
        self.assertEqual(sorted(re.findall(r"`([\w-]+\.md)`", en)),
                         sorted(re.findall(r"`([\w-]+\.md)`", zh)),
                         "the two routers point at different assets")


class CiMatchesTheDeclarationTest(unittest.TestCase):
    def test_ci_pins_the_declared_floor(self):
        floor = declared_floor()
        self.assertIsNotNone(floor, "pyproject.toml declares no requires-python")
        self.assertIn(
            floor, python_versions_in_ci(),
            f"CI must run the floor the project declares ({floor}); it runs "
            f"{python_versions_in_ci()}")

    def test_both_ends_of_the_matrix_are_claimed_in_the_docs(self):
        versions = python_versions_in_ci()
        self.assertGreaterEqual(len(versions), 2,
                                "a single-version matrix cannot cover a declared "
                                "range — pin the floor and the highest measured")
        for name in ("README.md", "README.zh-CN.md"):
            text = (ROOT / name).read_text(encoding="utf-8")
            for v in versions:
                self.assertIn(v, text,
                              f"{name} does not document that CI runs {v}")

    def test_the_stdlib_only_count_is_the_suite_list_minus_textual(self):
        """Three pages state how many suites need no third-party package.

        Each is a count over `scripts/tests/`, so a new suite makes all three wrong
        without any code changing. Checked as a number, in whichever words the page
        uses, and a page that stops stating it fails too -- an absent claim is the
        same drift as a false one.
        """
        textual_suites = {"test_tui.py", "test_config.py"}
        suites = sorted(p.name for p in (SCRIPTS / "tests").glob("test_*.py"))
        self.assertEqual(len(suites), len(textual_suites) + 12,
                         "the suite list moved out from under this case's own "
                         "arithmetic -- review which suites import textual")
        expected = len(suites) - len(textual_suites)

        # Written out, not generated: a page that says "twenty" must be read, and
        # a word list with a hole in it turns a true sentence into a red suite.
        words = {name: n for n, name in enumerate(
            ("one", "two", "three", "four", "five", "six", "seven", "eight",
             "nine", "ten", "eleven", "twelve", "thirteen", "fourteen",
             "fifteen", "sixteen", "seventeen", "eighteen", "nineteen",
             "twenty"), start=1)}
        claim = re.compile(
            r"other\s+(\d+|[a-z]+)\s+(?:suites\s+)?(?:are|is)\s+"
            r"(?:standard-library|stdlib-only)")
        pages = {"AGENTS.md": ROOT / "AGENTS.md",
                 "baseline.md": DOCS / "baseline.md",
                 "compatibility.md": DOCS / "compatibility.md"}
        wrong, missing = [], []
        for name, page in pages.items():
            text = page.read_text(encoding="utf-8")
            found = list(claim.finditer(text))
            if not found:
                missing.append(name)
            for match in found:
                raw = match.group(1)
                value = int(raw) if raw.isdigit() else words.get(raw)
                self.assertIsNotNone(
                    value, f"{name}: '{raw}' is not a number this case reads")
                if value != expected:
                    wrong.append((name, raw, value))
        self.assertEqual(missing, [],
                         f"these pages no longer state the stdlib-only count at "
                         f"all: {missing}")
        self.assertEqual(
            wrong, [],
            f"{expected} of {len(suites)} suites are stdlib-only, but these pages "
            f"say otherwise: {wrong}")

    def test_the_baseline_states_its_own_date(self):
        """A number without a date reads as a standing guarantee. This tree grows
        while it is being measured, so every figure here expires."""
        text = (DOCS / "baseline.md").read_text(encoding="utf-8")
        self.assertRegex(text, r"20\d\d-\d\d-\d\d")
        self.assertIn("Re-measure", text)


if __name__ == "__main__":
    unittest.main()
